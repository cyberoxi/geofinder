#!/usr/bin/env python3
"""Build a standalone Windows desktop app (no pip install on target PC).

Produces:  dist/GeoFinder/GeoFinder.exe  (+ deps)
and a zip: dist/GeoFinder-Windows-portable.zip

Usage (from repo root, with venv active):
  python tools/windows_desktop/build.py
  python tools/windows_desktop/build.py --skip-zip
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIST_NAME = "GeoFinder"
ENTRY = ROOT / "desktop_app" / "app.py"
SPEC = Path(__file__).resolve().parent / "geofinder.spec"
OUT_DIR = ROOT / "dist" / DIST_NAME
ZIP_PATH = ROOT / "dist" / "GeoFinder-Windows-portable.zip"

# Bundled so first train / FastSAM need no Ultralytics download.
WEIGHT_CANDIDATES = (
    "yolov8n-seg.pt",
    "yolov8n.pt",
    "FastSAM-s.pt",
)

# Heavy / optional stacks PyInstaller often misses without collect_all.
COLLECT_ALL = (
    "PySide6",
    "ultralytics",
    "torch",
    "torchvision",
    "cv2",
    "rasterio",
    "onnx",
    "asf_search",
)

HIDDEN_IMPORTS = (
    "desktop_app",
    "desktop_app.gui.main_window",
    "desktop_app.gui.pipeline_actions",
    "desktop_app.gui.workers",
    "desktop_app.pipeline.auto",
    "desktop_app.training.trainer",
    "desktop_app.packaging.builder",
    "desktop_app.dataset.builder",
    "desktop_app.satellite",
    "shared",
    "shared.config",
    "shared.qt_compat",
    "shared.runtime_paths",
    "packaging",
    "packaging.version",
    "packaging.requirements",
    "yaml",
    "pandas",
    "numpy",
    "requests",
    "psutil",
)


def _ensure_pyinstaller() -> None:
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        print("Installing PyInstaller...")
        subprocess.check_call([sys.executable, "-m", "pip", "install", "pyinstaller>=6.3"])


def _write_spec() -> None:
    # Do NOT ship whole desktop_app/ as datas — desktop_app/packaging shadows
    # the PyPI `packaging` package. Modules are collected via Analysis imports.
    datas = [
        (str(ROOT / "config"), "config"),
    ]
    for name in WEIGHT_CANDIDATES:
        src = ROOT / name
        if src.is_file():
            datas.append((str(src), "."))

    datas_repr = ",\n        ".join(f"(r'{src}', r'{dest}')" for src, dest in datas)
    collect_repr = ", ".join(repr(p) for p in COLLECT_ALL)
    hidden_repr = ", ".join(repr(h) for h in HIDDEN_IMPORTS)

    spec = f"""# -*- mode: python ; coding: utf-8 -*-
# Auto-generated by tools/windows_desktop/build.py — do not edit by hand.
from PyInstaller.utils.hooks import collect_all

datas = [
        {datas_repr},
]
binaries = []
hiddenimports = [{hidden_repr}]

for pkg in [{collect_repr}]:
    try:
        d, b, h = collect_all(pkg)
        datas += d
        binaries += b
        hiddenimports += h
    except Exception as exc:
        print(f"collect_all({{pkg!r}}) skipped: {{exc}}")

a = Analysis(
    [r'{ENTRY.as_posix()}'],
    pathex=[r'{ROOT.as_posix()}'],
    binaries=binaries,
    datas=datas,
    hiddenimports=hiddenimports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[r'{(Path(__file__).resolve().parent / "runtime_hook.py").as_posix()}'],
    excludes=['pytest', 'IPython', 'jupyter', 'notebook', 'tkinter'],
    noarchive=False,
    optimize=0,
)
pyz = PYZ(a.pure)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='{DIST_NAME}',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=False,
    console=False,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
)
coll = COLLECT(
    exe,
    a.binaries,
    a.datas,
    strip=False,
    upx=False,
    upx_exclude=[],
    name='{DIST_NAME}',
)
"""
    SPEC.write_text(spec, encoding="utf-8")
    print(f"Wrote {SPEC}")


def _write_readme(dest: Path) -> None:
    text = """GeoFinder Desktop — نسخه قابل‌حمل ویندوز
========================================

نصب:
  1. این پوشه را هر جا خواستید کپی کنید (مثلاً Desktop یا C:\\GeoFinder).
  2. روی GeoFinder.exe دوبار کلیک کنید.
  3. نیازی به نصب Python یا pip نیست.

نکات:
  - برای آموزش با GPU، درایور NVIDIA باید روی سیستم نصب باشد.
  - پروژه‌ها و داده‌ها را در مسیر جدا نگه دارید؛ این پوشه فقط برنامه است.
  - مدل‌های پایه (yolov8n-seg.pt و در صورت وجود FastSAM-s.pt) همراه برنامه هستند.

GeoFinder Desktop — portable Windows build
==========================================

1. Copy this folder anywhere.
2. Double-click GeoFinder.exe.
3. No Python / pip install required.
"""
    (dest / "README-install.txt").write_text(text, encoding="utf-8")


def _zip_dist() -> None:
    if ZIP_PATH.exists():
        ZIP_PATH.unlink()
    print(f"Zipping -> {ZIP_PATH}")
    with zipfile.ZipFile(ZIP_PATH, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=5) as zf:
        for path in OUT_DIR.rglob("*"):
            if path.is_file():
                zf.write(path, Path(DIST_NAME) / path.relative_to(OUT_DIR))
    size_gb = ZIP_PATH.stat().st_size / (1024**3)
    print(f"Zip size: {size_gb:.2f} GB")


def main() -> int:
    parser = argparse.ArgumentParser(description="Build portable GeoFinder Desktop for Windows")
    parser.add_argument("--skip-zip", action="store_true", help="Do not create the zip archive")
    parser.add_argument("--clean", action="store_true", help="Remove previous build/dist output first")
    args = parser.parse_args()

    if not ENTRY.is_file():
        print(f"Missing entrypoint: {ENTRY}", file=sys.stderr)
        return 1

    _ensure_pyinstaller()
    _write_spec()

    if args.clean:
        for p in (ROOT / "build" / DIST_NAME, OUT_DIR, ROOT / "build"):
            if p.exists():
                print(f"Removing {p}")
                shutil.rmtree(p, ignore_errors=True)

    cmd = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--distpath",
        str(ROOT / "dist"),
        "--workpath",
        str(ROOT / "build"),
        str(SPEC),
    ]
    print("Running:", " ".join(cmd))
    subprocess.check_call(cmd, cwd=str(ROOT))

    if not (OUT_DIR / f"{DIST_NAME}.exe").is_file():
        print(f"Build failed — missing {OUT_DIR / f'{DIST_NAME}.exe'}", file=sys.stderr)
        return 1

    # Ensure weights sit next to the exe (easy for YOLO/FastSAM relative paths).
    for name in WEIGHT_CANDIDATES:
        src = ROOT / name
        if src.is_file():
            shutil.copy2(src, OUT_DIR / name)

    _write_readme(OUT_DIR)
    print(f"Ready: {OUT_DIR / f'{DIST_NAME}.exe'}")

    if not args.skip_zip:
        _zip_dist()
        print(f"Portable zip: {ZIP_PATH}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
